import os
import subprocess
import streamlit as st
import numpy as np
import pandas as pd
import yfinance as yf
from scipy.io import loadmat
import plotly.graph_objects as go

st.set_page_config(page_title="IV Surface Quant Engine", layout="wide")

st.title("Quantitative Implied Volatility Surface Engine")
st.write("Hybrid Architecture: Python/Streamlit Frontend + GNU Octave Math Engine")

# Sidebar Configuration
st.sidebar.header("Market & System Settings")
ticker_symbol = st.sidebar.text_input("Stock Ticker", value="AAPL")
octave_path_input = st.sidebar.text_input(
    "Path to octave-cli.exe", 
    value=r"C:\Program Files\GNU Octave\Octave-11.1.0\mingw64\bin\octave-cli.exe"
)

if st.button("Run Quantitative Simulation"):
    with st.spinner(f"Fetching real-world option chain for {ticker_symbol.upper()} and executing Octave engine..."):
        try:
            # 1. Fetch live market data via yfinance
            stock = yf.Ticker(ticker_symbol.strip().upper())
            hist = stock.history(period="5d")
            
            if hist.empty:
                raise ValueError(f"Could not fetch market data for ticker: {ticker_symbol}. Check symbol.")
                
            spot_price = hist['Close'].iloc[-1]
            expirations = stock.options
            
            if not expirations:
                raise ValueError(f"No option expiration chains found for {ticker_symbol}.")
                
            # Select up to 6 near-term expiration dates
            selected_exp = expirations[:min(6, len(expirations))]
            
            common_strikes = np.linspace(spot_price * 0.85, spot_price * 1.15, 20)
            maturities_list = []
            price_matrix = []
            today = pd.Timestamp.today()
            
            for exp in selected_exp:
                opt_chain = stock.option_chain(exp)
                calls = opt_chain.calls
                
                exp_date = pd.Timestamp(exp)
                T = (exp_date - today).days / 365.0
                if T <= 0:
                    continue
                    
                maturities_list.append(T)
                
                # Compute mid prices & CRITICAL FIX: Sort by strike for valid interpolation
                calls['mid'] = (calls['bid'] + calls['ask']) / 2
                calls['mid'] = calls['mid'].fillna(calls['lastPrice'])
                
                valid_calls = calls.dropna(subset=['mid']).sort_values('strike')
                
                if len(valid_calls) > 2:
                    interp_prices = np.interp(
                        common_strikes, 
                        valid_calls['strike'].values, 
                        valid_calls['mid'].values, 
                        left=np.nan, 
                        right=np.nan
                    )
                    price_matrix.append(interp_prices)
                else:
                    price_matrix.append(np.ones_like(common_strikes) * np.nan)
                    
            price_matrix = np.array(price_matrix)
            
            # Clean up NaNs using Black-Scholes intrinsic value floor fallback
            for r_idx in range(price_matrix.shape[0]):
                for c_idx in range(price_matrix.shape[1]):
                    if np.isnan(price_matrix[r_idx, c_idx]):
                        strike_val = common_strikes[c_idx]
                        price_matrix[r_idx, c_idx] = max(0.0, spot_price - strike_val) + 0.5
            
            K_grid, T_grid = np.meshgrid(common_strikes, maturities_list)
            
            if price_matrix.shape[0] < 2:
                raise ValueError("Insufficient expiration data points to build a 2D surface.")

            # 2. Write parameters to params.m for Octave
            with open("params.m", "w") as f:
                f.write(f"S = {spot_price};\n")
                f.write(f"r = 0.045;\n")
                f.write("K = " + np.array_str(K_grid, precision=4, suppress_small=True).replace('\n', '') + ";\n")
                f.write("T = " + np.array_str(T_grid, precision=4, suppress_small=True).replace('\n', '') + ";\n")
                f.write("market_prices = " + np.array_str(price_matrix, precision=4, suppress_small=True).replace('\n', '') + ";\n")
            
            octave_path = octave_path_input.strip()
            if not os.path.exists(octave_path):
                raise FileNotFoundError(f"Could not find octave-cli.exe at: {octave_path}. Update path in sidebar.")

            # 3. Trigger Octave via subprocess
            subprocess.run([octave_path, "--no-gui", "iv_surface.m"], check=True)
            
            # 4. Load results generated by Octave
            data = loadmat("results.mat")
            K = data["K"]
            T = data["T"]
            IV = data["IV"]
            
            st.success(f"Successfully computed Implied Volatility Surface for {ticker_symbol.upper()} (Spot: ${spot_price:.2f})!")
            
            # =========================================================
            # RENDER PLOTS IN STREAMLIT (Matching Octave's 3-Window Setup)
            # =========================================================
            
            # --- PLOT 1: 3D Implied Volatility Surface ---
            st.subheader("1. 3D Implied Volatility Surface")
            surface = go.Surface(
                x=K, y=T, z=IV, 
                surfacecolor=IV, 
                colorscale="Viridis",
                colorbar=dict(title="Volatility (\sigma)")
            )
            fig1 = go.Figure(data=[surface])
            fig1.update_layout(
                scene=dict(
                    xaxis_title="Strike Price (K)",
                    yaxis_title="Time to Maturity (T)",
                    zaxis_title="Implied Volatility (\sigma)"
                ),
                height=550,
                margin=dict(l=0, r=0, t=30, b=0)
            )
            st.plotly_chart(fig1, use_container_width=True)
            
            # Create two columns for the 2D cross-section plots
            col1, col2 = st.columns(2)
            
            # --- PLOT 2: 2D Volatility Smile Cross-Section ---
            with col1:
                st.subheader("2. Volatility Smile (Strike Slice)")
                mid_row = round(K.shape[0] / 2)
                fig2 = go.Figure()
                fig2.add_trace(go.Scatter(
                    x=K[mid_row, :], 
                    y=IV[mid_row, :], 
                    mode='lines+markers', 
                    line=dict(color='firebrick', width=3),
                    marker=dict(size=8)
                ))
                fig2.update_layout(
                    xaxis_title="Strike Price (K)",
                    yaxis_title="Implied Volatility (\sigma)",
                    height=400,
                    margin=dict(l=0, r=0, t=30, b=0)
                )
                st.plotly_chart(fig2, use_container_width=True)
                
            # --- PLOT 3: 2D Term Structure Cross-Section ---
            with col2:
                st.subheader("3. Term Structure (Maturity Slice)")
                mid_col = round(K.shape[1] / 2)
                fig3 = go.Figure()
                fig3.add_trace(go.Scatter(
                    x=T[:, mid_col], 
                    y=IV[:, mid_col], 
                    mode='lines+markers', 
                    line=dict(color='royalblue', width=3),
                    marker=dict(size=8)
                ))
                fig3.update_layout(
                    xaxis_title="Time to Maturity (T)",
                    yaxis_title="Implied Volatility (\sigma)",
                    height=400,
                    margin=dict(l=0, r=0, t=30, b=0)
                )
                st.plotly_chart(fig3, use_container_width=True)
            
        except Exception as e:
            st.error(f"Error during execution: {e}")
            
        # Cleanup temporary parameter file
        if os.path.exists("params.m"):
            os.remove("params.m")